"""Audio-description feed — deterministic narration generated from event data.

Broadcast audio description fills the commentary's gaps by describing what a
sighted viewer would see: who has the ball, where on the pitch, what they did
with it. Because every synthetic event carries positions, outcomes and body
part, this is generated by code — no model, no credentials, always on. It is
also the only feed that is verifiable by construction: every noun in the line
came from the event ledger, so nothing it says can drift from the numbers.

Only meaningful actions are described (goals, shots, cards, set pieces,
substitutions, formations). Routine passes and carries return ``None`` — the
describer stays quiet during them, exactly like a real AD track.
"""

from __future__ import annotations

from src.events.schema import Event, EventType


def _channel(y: float) -> str:
    if y < 26.7:
        return "left"
    if y > 53.3:
        return "right"
    return "central"


def _zone(x: float) -> str:
    if x >= 80:
        return "in the final third"
    if x >= 40:
        return "in midfield"
    return "deep in their own half"


def _body_part(e: Event) -> str:
    bp = e.metadata.get("body_part", "right_foot")
    return {
        "right_foot": "his right foot",
        "left_foot": "his left foot",
        "head": "his head",
    }.get(str(bp), "his right foot")


def describe_event(e: Event, home_team: str = "Home", away_team: str = "Away") -> str | None:
    """Describe one event for the audio feed, or None if it isn't describable."""
    team = home_team if e.team.value == "Home" else away_team
    # real-data events carry no coordinates (metadata.position_estimated) —
    # narrate the area honestly rather than invent a channel
    estimated = bool(e.metadata.get("position_estimated"))
    where = "in the area" if estimated else f"on the {_channel(e.position.y)}"
    where_full = (
        "in the area" if estimated else f"from the {_channel(e.position.y)} {_zone(e.position.x)}"
    )
    zone = "in the area" if estimated else _zone(e.position.x)

    if e.type == EventType.GOAL:
        return (
            f"Goal for {team}. {e.player} meets it {where} and finishes "
            f"with {_body_part(e)} — the net bulges and the crowd is on its feet."
        )
    if e.type == EventType.SHOT:
        outcome = e.outcome or ""
        if outcome == "on_target":
            return (
                f"{e.player} lets fly {where_full} with {_body_part(e)} — "
                f"the goalkeeper has to get down to it."
            )
        return f"{e.player} shoots {where_full} with {_body_part(e)} — it sails away from goal."
    if e.type == EventType.TACKLE:
        if e.outcome == "success":
            return f"{e.player} slides in {zone} and wins the ball cleanly for {team}."
        return f"{e.player} goes to ground {zone} but the attacker skips past him."
    if e.type == EventType.FOUL:
        card = str(e.metadata.get("card", e.outcome or "none"))
        if card in ("yellow", "red"):
            return f"The referee stops play {zone} — {e.player} of {team} is shown the {card} card."
        return f"{e.player} is penalised for the challenge {zone}; free kick to the opposition."
    if e.type == EventType.SET_PIECE:
        kind = str(e.metadata.get("set_piece_type", "set piece")).replace("_", " ")
        return f"{team} have a {kind} {where}; {e.player} stands over it."
    if e.type == EventType.SUBSTITUTION:
        player_in = e.metadata.get("player_in")
        if player_in:
            return f"A change for {team} — {player_in} comes on in place of {e.player}."
        return f"{team} make a substitution."
    if e.type == EventType.FORMATION_CHANGE:
        formation = e.metadata.get("formation")
        if formation:
            return f"{team} line up in a {formation}."
        return None
    return None


def audio_line(e: Event, home_team: str = "Home", away_team: str = "Away") -> dict | None:
    """An AD line as a commentary-shaped frame, or None for routine events."""
    text = describe_event(e, home_team, away_team)
    if text is None:
        return None
    return {
        "id": f"ad:{e.id}",
        "minute": e.minute,
        "second": e.second,
        "text": text,
        "tone": "audio-description",
        "insight_ids": [],
        "verification": None,
        "audience": "ad",
    }
